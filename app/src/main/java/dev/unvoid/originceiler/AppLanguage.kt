/**
 * In-app language (English / Russian). The UI is written in English; [Text] below shadows the
 * Material one in the UI files and translates every literal through [RUSSIAN], so screens need no
 * per-string changes. Strings without an entry (app names, values) are shown as they are.
 */
object AppLanguage {
    const val ENGLISH = "en"
    const val RUSSIAN = "ru"
    private const val PREFERENCES = "settings"
    private const val KEY = "app_language"

    var current by mutableStateOf(ENGLISH)
        private set

    fun init(context: Context) {
        val stored = context.getSharedPreferences(PREFERENCES, 0).getString(KEY, null)
        current = stored ?: if (Locale.getDefault().language == RUSSIAN) RUSSIAN else ENGLISH
    }

    fun set(context: Context, language: String) {
        current = language
        context.getSharedPreferences(PREFERENCES, 0).edit().putString(KEY, language).commit()
    }
}

fun tr(text: String): String {
    if (AppLanguage.current != AppLanguage.RUSSIAN || text.isEmpty()) return text
    RUSSIAN[text]?.let { return it }
    // Messages built from templates: translate the fixed part, keep the inserted values.
    TEMPLATES.firstNotNullOfOrNull { (pattern, russian) ->
        pattern.matchEntire(text)?.let { match -> russian.replace("$1", match.groupValues[1]) }
    }?.let { return it }
    // Section headers are uppercased before they reach Text.
    if (text == text.uppercase()) {
        RUSSIAN_BY_LOWERCASE[text.lowercase()]?.let { return it.uppercase() }
    }
    return text
}

